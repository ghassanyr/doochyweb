// .env generation and merging for the setup CLI.
//
// The setup CLI must be safe to re-run: it updates only the keys it owns, keeps
// comments and unrelated settings, and always leaves a backup of the previous
// file. Secrets are written with mode 0600 on POSIX; Windows inherits the user
// profile ACL.

import fs from "node:fs";
import path from "node:path";

import dotenv from "dotenv";

const KEY_RE = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/;

/** Parse an existing .env without mutating process.env. */
export function parseEnv(content: string): Record<string, string> {
  return dotenv.parse(content);
}

/**
 * Quote a value only when the .env format needs it. Generated secrets are
 * base64 or base64url and need no quoting; a pasted Mongo URI might.
 */
export function formatEnvValue(value: string): string {
  if (value === "") return "";
  if (/[\s#]/.test(value)) {
    if (!value.includes("'")) return `'${value}'`;
    if (!value.includes('"')) return `"${value}"`;
    return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
  }
  return value;
}

/**
 * Merge owned keys into an existing .env. Owned keys are replaced in place,
 * duplicate owned keys are collapsed, and missing owned keys are appended in a
 * labelled block. Everything else is preserved exactly.
 */
export function mergeEnvFile(existing: string, updates: Record<string, string>): string {
  const owned = new Set(Object.keys(updates));
  const written = new Set<string>();
  const lines = existing.replace(/\r\n/g, "\n").split("\n");
  const out: string[] = [];

  for (const line of lines) {
    const match = KEY_RE.exec(line);
    if (match && owned.has(match[1])) {
      const key = match[1];
      if (!written.has(key)) {
        out.push(`${key}=${formatEnvValue(updates[key])}`);
        written.add(key);
      }
      continue;
    }
    out.push(line);
  }

  while (out.length > 0 && out[out.length - 1].trim() === "") out.pop();

  const missing = Object.keys(updates).filter((key) => !written.has(key));
  if (missing.length > 0) {
    if (out.length > 0) out.push("");
    out.push("# Added by pnpm doochy:setup");
    for (const key of missing) {
      out.push(`${key}=${formatEnvValue(updates[key])}`);
    }
  }

  return `${out.join("\n")}\n`;
}

/** First-run template. Kept short on purpose; .env.example documents extras. */
export function renderNewEnvFile(values: Record<string, string>): string {
  const line = (key: string) => `${key}=${formatEnvValue(values[key] ?? "")}`;
  return [
    "# Doochy environment. Generated by pnpm doochy:setup.",
    "# Optional settings are documented in .env.example.",
    "",
    "# HTTP port. The server binds to 127.0.0.1 only.",
    line("PORT"),
    "",
    "# MongoDB. The default Docker setup binds to loopback only.",
    line("MONGO_URI"),
    line("MONGO_DB"),
    "",
    "# Secrets generated by setup. Keep this file private.",
    line("JWT_SECRET"),
    line("INTEGRATIONS_ENCRYPTION_KEY"),
    line("TRAINER_ITEM_SECRET"),
    "",
    "# Public URL used in links and OAuth callbacks.",
    line("PUBLIC_BASE_URL"),
    "",
  ].join("\n");
}

function timestamp(): string {
  return new Date().toISOString().replace(/[:.]/g, "-");
}

export interface WriteResult {
  backup: string | null;
}

/** Back up an existing file, then write atomically where the OS allows it. */
export function writeEnvFile(envPath: string, content: string): WriteResult {
  fs.mkdirSync(path.dirname(envPath), { recursive: true });

  let backup: string | null = null;
  if (fs.existsSync(envPath)) {
    backup = `${envPath}.backup-${timestamp()}`;
    fs.copyFileSync(envPath, backup);
  }

  const tmp = `${envPath}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, content, { encoding: "utf8", mode: 0o600 });
  try {
    fs.renameSync(tmp, envPath);
  } catch {
    // Windows can refuse to rename over an existing file.
    fs.rmSync(envPath, { force: true });
    fs.renameSync(tmp, envPath);
  }
  if (process.platform !== "win32") fs.chmodSync(envPath, 0o600);

  return { backup };
}
