import assert from "node:assert/strict";
import { describe, test } from "node:test";

import {
  MONGO_CONTAINER,
  MONGO_VOLUME,
  renderCompose,
} from "../src/server/setup/compose";
import {
  formatEnvValue,
  mergeEnvFile,
  parseEnv,
  renderNewEnvFile,
} from "../src/server/setup/envFile";
import {
  MONGO_DB_NAME,
  isLocalMongoUri,
  isMongoUri,
  redactMongoUri,
} from "../src/server/setup/mongo";
import {
  generateEncryptionKey,
  generateJwtSecret,
  generateTrainerSecret,
  isUsableJwtSecret,
  isValidEncryptionKey,
} from "../src/server/setup/secrets";
import { normalizePublicUrl } from "../src/server/setup/url";

describe("setup env file", () => {
  test("quotes only values that need it", () => {
    assert.equal(formatEnvValue(""), "");
    assert.equal(formatEnvValue("9111"), "9111");
    assert.equal(formatEnvValue("mongodb://127.0.0.1:27017"), "mongodb://127.0.0.1:27017");
    assert.equal(formatEnvValue("hello world"), "'hello world'");
    assert.equal(formatEnvValue("pass#word"), "'pass#word'");
  });

  test("updates owned keys, preserves comments and unrelated keys", () => {
    const existing = [
      "# keep me",
      "PORT=9000",
      "CUSTOM=value",
      "MONGO_DB=old",
      "",
    ].join("\n");

    const merged = mergeEnvFile(existing, {
      PORT: "9111",
      MONGO_DB: "doochy",
      JWT_SECRET: "secret",
    });

    assert.equal(merged.includes("# keep me"), true);
    assert.equal(merged.includes("CUSTOM=value"), true);
    assert.equal(merged.includes("PORT=9111"), true);
    assert.equal(merged.includes("MONGO_DB=doochy"), true);
    assert.equal(merged.includes("JWT_SECRET=secret"), true);
    assert.equal(merged.includes("PORT=9000"), false);
  });

  test("collapses duplicate owned keys and appends missing ones once", () => {
    const existing = ["PORT=1", "PORT=2", "OTHER=x", ""].join("\n");
    const merged = mergeEnvFile(existing, { PORT: "9111", MONGO_DB: "doochy" });

    assert.equal(merged.match(/^PORT=/gm)?.length, 1);
    assert.equal(merged.match(/^MONGO_DB=/gm)?.length, 1);
    assert.equal(merged.includes("# Added by pnpm doochy:setup"), true);
  });

  test("round-trips quoted values through the dotenv parser", () => {
    const content = mergeEnvFile("", {
      MONGO_URI: "mongodb://user:p#ss@example.com:27017",
      PUBLIC_BASE_URL: "https://example.com",
    });
    const parsed = parseEnv(content);
    assert.equal(parsed.MONGO_URI, "mongodb://user:p#ss@example.com:27017");
    assert.equal(parsed.PUBLIC_BASE_URL, "https://example.com");
  });

  test("first-run template uses the new database name", () => {
    const content = renderNewEnvFile({
      PORT: "9111",
      MONGO_URI: "mongodb://127.0.0.1:27017",
      MONGO_DB: MONGO_DB_NAME,
      JWT_SECRET: "jwt",
      INTEGRATIONS_ENCRYPTION_KEY: "key",
      TRAINER_ITEM_SECRET: "trainer",
      PUBLIC_BASE_URL: "http://localhost:9111",
    });
    assert.equal(content.includes("MONGO_DB=doochy"), true);
    assert.equal(content.includes("Generated by pnpm doochy:setup"), true);
  });
});

describe("setup compose file", () => {
  test("uses the doochy names and loopback binding", () => {
    const compose = renderCompose(27018);
    assert.equal(compose.includes("image: mongo:7.0"), true);
    assert.equal(compose.includes(`container_name: ${MONGO_CONTAINER}`), true);
    assert.equal(compose.includes(`${MONGO_VOLUME}:/data/db`), true);
    assert.equal(compose.includes('"127.0.0.1:27018:27017"'), true);
    assert.equal(compose.includes("restart: unless-stopped"), true);
    assert.equal(compose.includes("healthcheck:"), true);
  });
});

describe("setup secrets", () => {
  test("generates valid secrets", () => {
    const jwt = generateJwtSecret();
    const encryption = generateEncryptionKey();
    const trainer = generateTrainerSecret();

    assert.equal(isUsableJwtSecret(jwt), true);
    assert.equal(isValidEncryptionKey(encryption), true);
    assert.equal(trainer.length > 20, true);
    assert.notEqual(generateJwtSecret(), jwt);
  });

  test("rejects short JWT secrets", () => {
    assert.equal(isUsableJwtSecret(""), false);
    assert.equal(isUsableJwtSecret("short"), false);
    assert.equal(isUsableJwtSecret("x".repeat(31)), false);
    assert.equal(isUsableJwtSecret("x".repeat(32)), true);
  });

  test("rejects invalid encryption keys", () => {
    assert.equal(isValidEncryptionKey(""), false);
    assert.equal(isValidEncryptionKey("not-base64"), false);
    assert.equal(isValidEncryptionKey(Buffer.alloc(16, 1).toString("base64")), false);
  });
});

describe("setup mongo helpers", () => {
  test("redacts credentials from a URI", () => {
    assert.equal(
      redactMongoUri("mongodb://user:secret@example.com:27017/doochy"),
      "mongodb://***:***@example.com:27017/doochy"
    );
    assert.equal(
      redactMongoUri("mongodb+srv://user:secret@cluster.example.com/doochy"),
      "mongodb+srv://***:***@cluster.example.com/doochy"
    );
    assert.equal(
      redactMongoUri("mongodb://127.0.0.1:27017"),
      "mongodb://127.0.0.1:27017"
    );
  });

  test("recognises Mongo URIs and local hosts", () => {
    assert.equal(isMongoUri("mongodb://127.0.0.1:27017"), true);
    assert.equal(isMongoUri("mongodb+srv://cluster.example.com"), true);
    assert.equal(isMongoUri("http://example.com"), false);

    assert.equal(isLocalMongoUri("mongodb://127.0.0.1:27017"), true);
    assert.equal(isLocalMongoUri("mongodb://localhost:27017"), true);
    assert.equal(isLocalMongoUri("mongodb://db.example.com:27017"), false);
  });

  test("keeps the new database name", () => {
    assert.equal(MONGO_DB_NAME, "doochy");
  });
});

describe("setup public URL", () => {
  test("falls back to localhost", () => {
    assert.equal(normalizePublicUrl("", 9111), "http://localhost:9111");
    assert.equal(normalizePublicUrl("localhost:9111", 9111), "http://localhost:9111");
    assert.equal(normalizePublicUrl("127.0.0.1:9111", 9111), "http://127.0.0.1:9111");
  });

  test("adds https to a bare domain and strips trailing slashes", () => {
    assert.equal(normalizePublicUrl("example.com", 9111), "https://example.com");
    assert.equal(normalizePublicUrl("example.com/", 9111), "https://example.com");
    assert.equal(
      normalizePublicUrl("https://example.com/", 9111),
      "https://example.com"
    );
  });

  test("rejects values that cannot be parsed", () => {
    assert.throws(() => normalizePublicUrl("http://", 9111));
  });
});
